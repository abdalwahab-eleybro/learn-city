"""Generates js/20b-easy-predict.js: for each built-in problem a (call, result) pair where the result was
produced by RUNNING the model solution. usage: make-predict.py <problems.json> <harness.py> <out.js>"""
import json, sys, copy, ast, importlib.util
IN, HARNESS, OUT = sys.argv[1:4]
spec = importlib.util.spec_from_file_location('h', HARNESS); h = importlib.util.module_from_spec(spec); spec.loader.exec_module(h)
P = json.load(open(IN))
def lit(v):
    if isinstance(v,(bool,int,str)) and not isinstance(v,float): return True
    if isinstance(v,(list,tuple)): return all(lit(x) for x in v)
    return False
out={}
for p in P:
    code=p['code']
    name,params=h._first_def(code)
    # model function = the one named by the problem's solution? use first def, except helpers
    env=h._example_env(p['input'])
    if not env: continue
    ns={}
    try: exec(code,ns)
    except Exception: continue
    # pick the def whose params are all in env
    import ast
    fn=None
    for n in ast.parse(code).body:
        if isinstance(n,ast.FunctionDef) and all(a.arg in env for a in n.args.args): fn=n
    if not fn: continue
    # prefer last def that fits? earlier work used learner's name; choose first fitting
    for n in ast.parse(code).body:
        if isinstance(n,ast.FunctionDef) and all(a.arg in env for a in n.args.args): fn=n;break
    args=[env[a.arg] for a in fn.args.args]
    try: r=ns[fn.name](*copy.deepcopy(args))
    except Exception: continue
    if not lit(r): continue
    if isinstance(r,tuple): r=list(r)
    call=fn.name+'('+', '.join(repr(a) for a in args)+')'
    if len(call)>70 or len(repr(r))>40: continue
    out[p['num']]={'call':call,'out':repr(r)}
print(len(out))
js="/* GENERATED by tools/make-predict.js (npm run gen:predict). Do not edit. Real-Python-verified (call, result) pairs for predict-the-output questions */\nwindow.CF=window.CF||{};CF.EasyData=CF.EasyData||{};\nCF.EasyData.PREDICT="+json.dumps(out,indent=0)+";\n"
open(OUT,'w').write(js)
