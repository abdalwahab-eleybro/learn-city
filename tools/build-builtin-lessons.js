#!/usr/bin/env node
/* Generates js/29-lessons-builtin.js from tools/builtin-lessons-src.js.
   Every lesson is validated, its Python is RUN (boss model passes its own tests, predict output is real,
   code compiles) and its trace visuals are recorded from real execution. Needs python3.   */
const fs = require('fs'), path = require('path');
const T = require('../tests/lib');
if (!T.hasPython) { console.error('python3 is required'); process.exit(1); }
const ctx = T.load(T.LESSON_STACK); T.usePython(ctx);
const L = ctx.CF.AILessons;
(async () => {
  const lessons = require('./builtin-lessons-src.js'), out = []; let bad = 0;
  for (const { id, script } of lessons) {
    const e = L.validate(script); if (e.length) { console.log(id, 'INVALID', e); bad++; continue; }
    const v = await L.verify(script); if (v.errors.length || (v.skipped && !v.general)) { console.log(id, 'VERIFY', v); bad++; continue; }
    const r = L.isGeneral(script) ? { errors: [] } : await L.resolveTraces(script); if (r.errors.length) { console.log(id, 'TRACE', r.errors); bad++; continue; }
    script.verified = !L.isGeneral(script); L.buildQuestions(script, id);
    console.log('ok  ', id); out.push({ id, script });
  }
  if (bad) process.exit(1);
  const js = `/* ═══════════════════════════════════════════════════════════ */
/*  29-lessons-builtin.js — lessons that ship with the app        */
/*  GENERATED by tools/build-builtin-lessons.js from               */
/*  tools/builtin-lessons-src.js. Do not edit by hand.             */
/*  Every lesson was run with real Python: boss tests pass for the */
/*  model solution, predict outputs are real, and trace visuals    */
/*  were recorded from real execution (call stack included).       */
/*  They work with no API key and no internet. Depends on 24.      */
/* ═══════════════════════════════════════════════════════════ */
(function () {
  const L = [
${out.map(o => '    [' + JSON.stringify(o.id) + ', ' + JSON.stringify(o.script) + ']').join(',\n')}
  ];
  L.forEach(([id, script]) => CF.AILessons.addBuiltin(id, script));
})();
`;
  fs.writeFileSync(path.join(T.ROOT, 'js', '29-lessons-builtin.js'), js); console.log('wrote js/29-lessons-builtin.js (' + js.length + ' bytes)');
})();
