const T = require('../lib');
const ctx = T.load(['23-visuals'], { state: false });
const V = ctx.CF.Visuals, C = V._compute;
T.test('hashmap, set, venn, tuple frames and visual validation', () => {
  const fails = [];
  const assert = (c, m) => { if (!c) fails.push(m); };
  let f=C.hashmapFrames({buckets:5,ops:[{op:'put',key:'cat',value:1},{op:'put',key:'act',value:2},{op:'get',key:'act'},{op:'put',key:'cat',value:9},{op:'get',key:'dog'},{op:'delete',key:'cat'},{op:'in',key:'cat'}]});
  assert(f[1].hl.status==='ok'&&f[1].hash.includes('312'),'put cat '+f[1].hash);
  assert(f[2].hl.status==='collision'&&f[2].buckets[2].length===2,'collision');
  assert(f[3].hl.status==='ok','get');
  assert(f[4].hl.status==='update'&&f[4].buckets[2][0].v===9,'update');
  assert(f[5].hl.status==='error','keyerror '+f[5].hl.status);
  assert(f[6].buckets[2].length===1,'delete');
  assert(f[7].hl.status==='miss','in miss');
  let s=C.setFrames({start:[1,2,2],ops:[{op:'add',value:2},{op:'add',value:3},{op:'remove',value:9},{op:'discard',value:9},{op:'in',value:3}]});
  assert(s[0].items.length===2,'dedupe');assert(s[1].hl.status==='dup'&&s[1].items.length===2,'dup add');assert(s[2].items.length===3,'add');
  assert(s[3].hl.status==='error','remove err');assert(s[4].hl.status==='dup','discard');assert(s[5].hl.status==='ok','in');
  let v=C.vennCompute(['a','b','c'],['b','c','d']);
  assert(v.ops.intersection.result.join()==='b,c','inter');assert(v.ops.difference.result.join()==='a','diff');assert(v.ops.symmetric.result.join()==='a,d','sym');assert(v.ops.union.result.length===4,'union');
  let t=C.tupleFrames({values:[10,20,30],ops:[{op:'index',i:-1},{op:'assign',i:0,value:5},{op:'rebuild',i:1,value:99},{op:'slice',a:0,b:2},{op:'unpack',names:['x','y','z']}]});
  assert(t[1].hl[0]===2,'neg index');assert(t[2].error&&t[2].values[0]===10,'assign');assert(t[3].next[1]===99&&t[3].values[1]===20,'rebuild');assert(t[4].next.length===2,'slice');assert(t[5].names.length===3,'unpack');
  assert(V.validate({type:'hashmap',buckets:5,ops:[{op:'put',key:'a',value:1}]}).length===0,'valid hm');
  assert(V.validate({type:'hashmap',buckets:99,ops:[]}).length>0,'invalid hm');
  assert(V.validate({type:'tuple',values:[1,2],ops:[{op:'index',i:5}]}).length>0,'bad idx');
  assert(V.validate({type:'stepper',code:['x = 1'],steps:[{line:0,caption:'a'},{line:3,caption:'b'}]}).length>0,'bad line');
  assert(V.validate({type:'branch',branches:[{test:'a',does:'b'},{test:'else',does:'c'}],cases:[{label:'x',takes:2,why:'w'}]}).length>0,'bad takes');
  assert(V.validate({type:'nope'}).length>0,'unknown');assert(V.validate(null).length>0,'null');
  if (fails.length) throw new Error('failed: ' + fails.join(' | '));
});
